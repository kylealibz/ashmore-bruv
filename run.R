# Run from the project root: Rscript --vanilla run.R
source("R/reproduction.R")
source("R/simulation.R")
source("R/plots.R")
dir.create("results", showWarnings = FALSE)
reproduction <- reproduce_bouts()
simulation <- simulate_designs()
write.csv(reproduction$groups, "results/bout-means.csv", row.names = FALSE)
write.csv(reproduction$contrasts, "results/bout-contrasts.csv", row.names = FALSE)
write.csv(reproduction$sample, "results/observed-sample.csv", row.names = FALSE)
write.csv(reproduction$video_sd, "results/video-sd.csv", row.names = FALSE)
write.csv(simulation$replicates, "results/simulation-replicates.csv", row.names = FALSE)
write.csv(simulation$summary, "results/simulation-summary.csv", row.names = FALSE)
writeLines(capture.output(sessionInfo()), "results/session-info.txt")
save_chart("results/reproduced-bout-means.png", function() plot_bouts(reproduction$groups))
save_chart("results/equal-effort.png", function() plot_effort(simulation$summary))
save_chart("results/design-grid.png", function() plot_grid(simulation$summary))
print(reproduction$contrasts, row.names = FALSE)
print(simulation$summary[simulation$summary$scored_per_year == 144, ], row.names = FALSE)
